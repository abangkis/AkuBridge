import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCHEMA_VERSION } from './src/core.mjs';

const root = fileURLToPath(new URL('./', import.meta.url));
const digest = text => createHash('sha256').update(text).digest('hex');

async function publish(directory, name, text) {
  const temporary = join(directory, `.${name}.${randomUUID()}.tmp`);
  try {
    await writeFile(temporary, text, { flag: 'wx' });
    await rename(temporary, join(directory, name));
  } finally {
    await rm(temporary, { force: true });
  }
}

export async function buildSharedDOMEngine(directory = join(root, 'dist')) {
  const [input, metadata] = await Promise.all([
    readFile(join(root, 'src', 'core.mjs'), 'utf8'),
    readFile(join(root, 'package.json'), 'utf8'),
  ]);
  const core = input.replaceAll('\r\n', '\n');
  const exports = '\nexport { assessDOM, resolveDOMIdentity, SCHEMA_VERSION };\n';
  if (!core.endsWith(exports)) throw new Error('Unexpected SharedDOMEngine export declaration');
  const browser = `// Generated by build.mjs\n(() => {\n${core.slice(0, -exports.length)}\n\n` +
    `globalThis.AkuSharedDOMEngine = Object.freeze({ assessDOM, resolveDOMIdentity, SCHEMA_VERSION });\n})();\n`;
  const artifacts = { 'core.mjs': core, 'browser-runtime.js': browser };
  const manifest = {
    packageVersion: JSON.parse(metadata).version,
    schemaVersion: SCHEMA_VERSION,
    algorithm: 'sha256',
    source: { path: 'src/core.mjs', sha256: digest(core) },
    artifacts: Object.fromEntries(Object.entries(artifacts).map(([name, text]) => [name, { sha256: digest(text) }])),
  };
  await mkdir(directory, { recursive: true });
  for (const [name, text] of Object.entries(artifacts)) await publish(directory, name, text);
  await publish(directory, 'artifact-manifest.json', JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = await buildSharedDOMEngine();
  if (process.argv.includes('--stage-browser')) {
    await publish(root, 'browser-runtime.js', await readFile(join(root, 'dist', 'browser-runtime.js'), 'utf8'));
  }
  console.log(`SharedDOMEngine browser artifact SHA-256 ${manifest.artifacts['browser-runtime.js'].sha256}`);
}
